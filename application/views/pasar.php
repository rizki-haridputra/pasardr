// PHP: FUNGSI RENDER KIOS (DIPERBARUI)
// =====================================================================
function render_kios($kios) {
    // Memastikan ada nilai default jika data tidak ada untuk menghindari error
    $status = isset($kios['status']) ? htmlspecialchars($kios['status']) : 'kosong'; // Default status 'kosong'
    $jenis_kios = isset($kios['jKios']) ? htmlspecialchars($kios['jKios']) : 'N/A'; // Default jenis 'N/A'
    $harga_kios = isset($kios['hKios']) ? htmlspecialchars($kios['hKios']) : 'N/A';

    // Menggabungkan kelas status dan jenis kios untuk styling CSS
    $class_css = 'kios ' . $status . ' ' . $jenis_kios;

    echo '<div class="' . $class_css . '" 
               data-id="' . htmlspecialchars($kios['idKios']) . '" 
               data-status="' . htmlspecialchars($kios['status']) . '"
               data-j-kios="' . $jenis_kios . '"
               data-h-kios="' . $harga_kios . '"
               title="Kios ' . htmlspecialchars($kios['idKios']) . ' - Klik untuk detail">' 
               . htmlspecialchars($kios['idKios']) . 
         '</div>';
}

// Fungsi render blok inti (tidak berubah)
function render_blok_inti($data_grup) {
    foreach ($data_grup as $kolom_data) {
        echo '<div class="kolom-kios-inti">';
        foreach ($kolom_data as $kios) {
            render_kios($kios);
        }
        echo '</div>';
    }
}
