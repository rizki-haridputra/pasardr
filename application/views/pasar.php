<script>
document.addEventListener('DOMContentLoaded', function() {
    const modal = document.getElementById('modalKios');
    const tutupModal = document.querySelector('.modal-tutup');
    const denahContainer = document.querySelector('.denah-container');
    const modalKiosId = document.getElementById('modalKiosId');
    const modalKiosjKios = document.getElementById('modalKiosjKios');
    const modalKioshKios = document.getElementById('modalKioshKios');
    const modalKiosStatus = document.getElementById('modalKiosStatus');
    const modalKiosDeskripsi = document.getElementById('modalKiosDeskripsi');
    const tombolSewa = document.getElementById('tombolSewa');
    
    function bukaModal(id, status, jKios, hKios) {
      
        modalKiosId.textContent = id;
        modalKiosjKios.textContent = jKios;
        modalKioshKios.textContent = hKios;
        
        if (status === 'berisi') {
            modalKiosStatus.textContent = 'Berisi';
            modalKiosStatus.className = 'status-label berisi';
            modalKiosDeskripsi.textContent = 'Kios ini saat ini sudah disewa dan tidak tersedia untuk disewa kembali.';
            tombolSewa.textContent = 'Sudah Disewa';
            tombolSewa.classList.add('disabled');
            tombolSewa.removeAttribute('href');
        } 
        else if (status === 'proses') {
            modalKiosStatus.textContent = 'Proses';
            modalKiosStatus.className = 'status-label proses';
            modalKiosDeskripsi.textContent = 'Kios ini saat ini sudah disewa dan tidak tersedia untuk disewa kembali.';
            tombolSewa.textContent = 'Sedang Diproses';
            tombolSewa.classList.add('disabled');
            tombolSewa.removeAttribute('href');
        } 
        else {
            modalKiosStatus.textContent = 'Kosong';
            
            modalKiosjKios.className = 'status-label kosong';
            modalKioshKios.className = 'status-label kosong';
            modalKiosStatus.className = 'status-label kosong';
            modalKiosDeskripsi.textContent = 'Kios ini tersedia untuk disewa. Klik tombol di bawah untuk melanjutkan ke halaman penyewaan.';
            tombolSewa.textContent = 'Sewa Sekarang';
            tombolSewa.classList.remove('disabled');
            tombolSewa.href = `<?= base_url('pedagang/sewa/form/') ?>${id}`;
        }
        
        document.body.classList.add('modal-terbuka');
    }
    
    function tutupFungsi() {
        document.body.classList.remove('modal-terbuka');
    }

    denahContainer.addEventListener('click', function(e) {
        const kios = e.target.closest('.kios');
        if (kios) {
            const id = kios.dataset.id;
            const status = kios.dataset.status;
            const jKios = kios.dataset.jKios;
            const hKios = kios.dataset.hKios;
            bukaModal(id, status, jKios, hKios);
        }
    });
    
    tutupModal.addEventListener('click', tutupFungsi);
    modal.addEventListener('click', function(e) {
        if (e.target === modal) {
            tutupFungsi();
        }
    });
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape' && document.body.classList.contains('modal-terbuka')) {
            tutupFungsi();
        }
    });
});
